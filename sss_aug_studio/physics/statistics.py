"""Stochastic models for sonar scattering statistics and environmental fields.

References
----------
* Abraham & Lyons (2002), IEEE J. Oceanic Eng. 27(4): K-distributed
  reverberation as gamma-modulated Rayleigh scattering (compound model).
* Lyons & Abraham (1999), JASA 106(3): shallow-water high-frequency seafloor
  backscatter statistics.
* Goodman (1976): fully developed speckle -> exponential intensity;
  L-look averaging -> Gamma(L, 1/L) multiplicative noise.
* Tough & Ward (1999), J. Phys. D: Appl. Phys. 32(23): correlated gamma and K
  processes generated by a memoryless nonlinear transformation of a Gaussian
  process -- the construction used here for every correlated gamma field.
* Ghosh & Henderson (2003), ACM TOMACS 13(3): the NORTA method in general.
"""

from __future__ import annotations

import numpy as np
from scipy.ndimage import gaussian_filter
from scipy.special import ndtr
from scipy.stats import gamma as _gamma_dist

__all__ = [
    "gamma_speckle",
    "k_texture_field",
    "correlated_gaussian_field",
    "colored_noise_1d",
]

# Nodes of the tabulated composite map z -> F^-1(Phi(z)).  8193 nodes over
# +-8 sigma reproduce ``scipy.stats.gamma.ppf`` to <= 1.2e-7 relative for every
# shape this package can request (0.3 <= k <= 50), which is below float32
# resolution; ``np.interp`` clamps beyond the grid, which is correct because
# P(|z| > 8) ~ 1e-15.
_PPF_TABLE_NODES = 8193
_PPF_TABLE_ZMAX = 8.0


def _correlated_gamma(
    rng: np.random.Generator,
    shape: tuple[int, int],
    k: float,
    corr_px: tuple[float, float],
) -> np.ndarray:
    """Unit-mean Gamma(k, 1/k) field with Gaussian spatial correlation.

    Exact marginal by construction (Tough & Ward 1999; the NORTA method,
    Ghosh & Henderson 2003): a unit-variance correlated Gaussian field is
    pushed through the normal CDF to uniforms and then through the gamma
    inverse CDF, a monotone memoryless map that leaves the marginal exactly
    Gamma(k, 1/k) while the Gaussian kernel sets the correlation structure.

    ``corr_px`` is the Gaussian **kernel sigma** per axis, not a correlation
    length; the achieved 1/e autocorrelation length is ~1.95 sigma.  The
    monotone map warps the correlation function slightly (Tough & Ward derive
    the warping), measured here at under 10% of the length scale.  Below
    0.3 px the kernel is a no-op and an uncorrelated draw is returned.
    """
    k = max(float(k), 0.3)
    sy, sx = corr_px
    if sy <= 0.3 and sx <= 0.3:
        return rng.gamma(shape=k, scale=1.0 / k, size=shape).astype(np.float32)
    z = correlated_gaussian_field(rng, shape, 1.0, (sy, sx)).astype(np.float64)
    z_nodes = np.linspace(-_PPF_TABLE_ZMAX, _PPF_TABLE_ZMAX, _PPF_TABLE_NODES)
    x_nodes = _gamma_dist.ppf(ndtr(z_nodes), a=k, scale=1.0 / k)
    return np.interp(z, z_nodes, x_nodes).astype(np.float32)


def gamma_speckle(
    rng: np.random.Generator,
    shape: tuple[int, ...],
    looks: float,
    corr_px: tuple[float, float] = (0.0, 0.0),
) -> np.ndarray:
    """Unit-mean multiplicative speckle for an L-look intensity image.

    Fully developed speckle gives exponential intensity (L=1); incoherent
    averaging of L looks gives Gamma(L, 1/L) with variance 1/L.  ``corr_px``
    optionally correlates the field over the resolution cell, as Gaussian
    kernel sigmas per axis; the marginal stays exactly Gamma(L, 1/L) either
    way (see :func:`_correlated_gamma`).
    """
    looks = max(float(looks), 0.25)
    if max(corr_px) <= 0.3:
        return rng.gamma(shape=looks, scale=1.0 / looks, size=shape).astype(np.float32)
    return _correlated_gamma(rng, shape, looks, corr_px)


def k_texture_field(
    rng: np.random.Generator,
    shape: tuple[int, int],
    nu: float,
    corr_px: tuple[float, float],
) -> np.ndarray:
    """Unit-mean gamma texture (the 'K' component) with spatial correlation.

    The compound (K) representation writes intensity as texture x speckle with
    texture ~ Gamma(nu, 1/nu); small ``nu`` = heavy tails (structured
    seabeds).  The marginal is exact at every ``nu`` and correlation length —
    :func:`_correlated_gamma` imposes correlation by transforming a Gaussian
    field rather than by smoothing a gamma one, so the third and higher
    moments survive.  ``corr_px`` is a Gaussian kernel sigma per axis.
    """
    return _correlated_gamma(rng, shape, nu, corr_px)


def correlated_gaussian_field(
    rng: np.random.Generator,
    shape: tuple[int, int],
    sigma_value: float,
    corr_px: tuple[float, float],
) -> np.ndarray:
    """Zero-mean Gaussian random field with given std and correlation lengths (px)."""
    white = rng.standard_normal(shape).astype(np.float32)
    sy, sx = max(corr_px[0], 0.01), max(corr_px[1], 0.01)
    f = gaussian_filter(white, sigma=(sy, sx), mode="reflect")
    std = float(f.std())
    if std < 1e-8:
        return np.zeros(shape, dtype=np.float32)
    return (f * (sigma_value / std)).astype(np.float32)


def colored_noise_1d(rng: np.random.Generator, n: int, sigma: float, corr_samples: float) -> np.ndarray:
    """Zero-mean band-limited (Gaussian-correlated) 1-D process of std ``sigma``.

    Used for yaw, speed and altitude perturbation time series along track;
    ``corr_samples`` is the correlation length expressed in samples (rows).
    """
    if n <= 0:
        return np.zeros(0, dtype=np.float32)
    white = rng.standard_normal(n).astype(np.float32)
    f = gaussian_filter(white, sigma=max(corr_samples, 0.01), mode="reflect")
    std = float(f.std())
    if std < 1e-8:
        return np.zeros(n, dtype=np.float32)
    return (f * (sigma / std)).astype(np.float32)
